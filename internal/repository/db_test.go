// baselineTables is the 16 tables of the baseline schema (including the migrations table).
var baselineTables = []string{
	"users", "kids", "subjects", "migrations", "metrics", "cursors", "tasks",
	"exams", "pages", "knowledge_points", "questions", "question_kps",
	"levels", "gaps", "messages", "kid_subjects",
}

func openTestDB(t *testing.T) *DB {
	t.Helper()
	db, err := Open(context.Background(), filepath.Join(t.TempDir(), "paperly.db"))
	require.NoError(t, err)
	t.Cleanup(func() { require.NoError(t, db.Close()) })
	return db
}

func TestOpenCreatesAllBaselineTables(t *testing.T) {
	ctx := context.Background()
	db := openTestDB(t)

	require.Len(t, baselineTables, 16, "基线表清单应为 16 张")

	for _, name := range baselineTables {
		var got string
		err := db.Read().QueryRowContext(
			ctx, `SELECT name FROM sqlite_master WHERE type='table' AND name=?`, name,
		).Scan(&got)
		require.NoError(t, err, "表 %s 应存在", name)
		require.Equal(t, name, got)
	}

	// 16 tables total. sqlite_sequence is generated by AUTOINCREMENT and must be excluded.
	var total int
	err := db.Read().QueryRowContext(ctx,
		`SELECT COUNT(*) FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'`,
	).Scan(&total)
	require.NoError(t, err)
	require.Equal(t, 16, total, "v1.0.0 应有 16 张表")
}

func TestMigrationBaselineWritten(t *testing.T) {
	ctx := context.Background()
	db := openTestDB(t)

	var version int
	var displayTag string
	err := db.Read().QueryRowContext(ctx,
		`SELECT version, display_tag FROM migrations WHERE version = 1`).Scan(&version, &displayTag)
	require.NoError(t, err)
	require.Equal(t, 1, version)
	require.Equal(t, "v1.0.0", displayTag)
}

func TestOpenIsIdempotent(t *testing.T) {
	ctx := context.Background()
	dbPath := filepath.Join(t.TempDir(), "paperly.db")

	db1, err := Open(ctx, dbPath)
	require.NoError(t, err)
	require.NoError(t, db1.Close())

	// Reopening must not write the migrations baseline row again.
	db2, err := Open(ctx, dbPath)
	require.NoError(t, err)
	defer func() { require.NoError(t, db2.Close()) }()

	var count int
	err = db2.Read().QueryRowContext(ctx, `SELECT COUNT(*) FROM migrations`).Scan(&count)
	require.NoError(t, err)
	require.Equal(t, 1, count)
}

func TestKidsAccessCodeUnique(t *testing.T) {
	ctx := context.Background()
	db := openTestDB(t)

	const ins = `INSERT INTO kids (name, access_code, grade, pin_hash) VALUES (?, ?, ?, ?)`
	_, err := db.Write().ExecContext(ctx, ins, "小明", "a7k2m9p4", 7, "!")
	require.NoError(t, err)

	_, err = db.Write().ExecContext(ctx, ins, "小红", "a7k2m9p4", 8, "!")
	require.Error(t, err)
}

func TestKidsPinHashNotNull(t *testing.T) {
	ctx := context.Background()
	db := openTestDB(t)

	// NOT NULL constraint regression: pin_hash does not allow omitting (NULL);
	// kids without a PIN are written a placeholder value by the service, not relying on NULL.
	const insNoPin = `INSERT INTO kids (name, access_code, grade) VALUES (?, ?, ?)`
	_, err := db.Write().ExecContext(ctx, insNoPin, "小明", "notnull1", 7)
	require.Error(t, err, "缺省 pin_hash 必须被 NOT NULL 约束拒绝")

	// A full row with pin_hash inserts fine; then the same access_code triggers the unique conflict.
	const insPin = `INSERT INTO kids (name, access_code, grade, pin_hash) VALUES (?, ?, ?, ?)`
	_, err = db.Write().ExecContext(ctx, insPin, "小明", "notnull1", 7, "!")
	require.NoError(t, err, "带 pin_hash 的完整行应可插入")
	_, err = db.Write().ExecContext(ctx, insPin, "小红", "notnull1", 8, "!")
	require.Error(t, err, "access_code 冲突仍应拒绝")
}

func TestKeyColumnsExist(t *testing.T) {
	ctx := context.Background()
	db := openTestDB(t)

	cases := []struct {
		table  string
		column string
	}{
		{"users", "pin_hash"},
		{"kids", "access_code"},
		{"kids", "grade"},
		{"migrations", "display_tag"},
		{"cursors", "task_name"},
		{"gaps", "severity"},
	}
	for _, c := range cases {
		var name string
		err := db.Read().QueryRowContext(ctx,
			`SELECT name FROM pragma_table_info(?) WHERE name = ?`, c.table, c.column,
		).Scan(&name)
		require.NoError(t, err, "%s.%s 应存在", c.table, c.column)
	}
}

func TestHealthProbesSchemaAndReturnsTag(t *testing.T) {
	ctx := context.Background()
	db := openTestDB(t)

	displayTag, err := db.Health(ctx)
	require.NoError(t, err)
	require.Equal(t, "v1.0.0", displayTag)

	// Break the schema: after dropping migrations, Health must error (Ping still passes).
	_, err = db.Write().ExecContext(ctx, `DROP TABLE migrations`)
	require.NoError(t, err)

	require.NoError(t, db.Ping(ctx), "Ping 只验证连接，删表后仍应通过")
	_, err = db.Health(ctx)
	require.Error(t, err, "Health 应检测到 schema 缺失")
}

// TestConcurrentReadsNoError covers PoC 7 scenario C: concurrent reads
// across read pool connections must be error-free.
func TestConcurrentReadsNoError(t *testing.T) {
	ctx := context.Background()
	db := openTestDB(t)

	var wg sync.WaitGroup
	errCh := make(chan error, 10)
	for w := 0; w < 10; w++ {
		wg.Add(1)
		go func() {
			defer wg.Done()
			for i := 0; i < 50; i++ {
				var n int
				if err := db.Read().QueryRowContext(ctx, `SELECT COUNT(*) FROM kids`).Scan(&n); err != nil {
					errCh <- fmt.Errorf("concurrent read failed: %w", err)
					return
				}
			}
		}()
	}
	wg.Wait()
	close(errCh)
	require.Empty(t, errCh, "并发读不应有错误")
}

// TestConcurrentWritesNoBusy covers PoC 7 scenario B: one write connection,
// immediate serialization, zero SQLITE_BUSY.
func TestConcurrentWritesNoBusy(t *testing.T) {
	ctx := context.Background()
	db := openTestDB(t)

	var wg sync.WaitGroup
	errCh := make(chan error, 10)
	for w := 0; w < 10; w++ {
		wg.Add(1)
		go func(worker int) {
			defer wg.Done()
			for i := 0; i < 50; i++ {
				_, err := db.Write().ExecContext(ctx,
					`INSERT INTO kids (name, access_code, grade, pin_hash) VALUES (?, ?, ?, ?)`,
					fmt.Sprintf("学生-%d-%d", worker, i), fmt.Sprintf("code-%d-%d", worker, i), 7, "!")
				if err != nil {
					errCh <- fmt.Errorf("concurrent write failed: %w", err)
					return
				}
			}
		}(w)
	}
	wg.Wait()
	close(errCh)
	require.Empty(t, errCh, "并发写不应有 SQLITE_BUSY")

	var count int
	require.NoError(t, db.Read().QueryRowContext(ctx, `SELECT COUNT(*) FROM kids`).Scan(&count))
	require.Equal(t, 500, count)
}
