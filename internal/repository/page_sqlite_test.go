// insertExamForPages inserts an exam row as the parent for pages' foreign key, returning its id.
func insertExamForPages(t *testing.T, db *DB) int64 {
	t.Helper()
	res, err := db.Write().ExecContext(context.Background(),
		`INSERT INTO exams (grade, uploaded_by) VALUES (9, 1)`)
	require.NoError(t, err)
	id, err := res.LastInsertId()
	require.NoError(t, err)
	return id
}

func TestPageRepoInsertListGetByID(t *testing.T) {
	ctx := context.Background()
	db := openTestDB(t)
	repo := NewPageRepoSQLite(db)
	examID := insertExamForPages(t, db)

	// Insert three pages (out of order); ListByExam must order by page_index ascending.
	for _, idx := range []int{3, 1, 2} {
		_, err := repo.Insert(ctx, &domain.Page{
			ExamID: examID, PageIndex: idx,
			FilePath: "/data/p" + string(rune('0'+idx)) + ".png", SHA256: "sha" + string(rune('0'+idx)),
		})
		require.NoError(t, err)
	}

	pages, err := repo.ListByExam(ctx, examID)
	require.NoError(t, err)
	require.Len(t, pages, 3)
	require.Equal(t, []int{1, 2, 3}, []int{pages[0].PageIndex, pages[1].PageIndex, pages[2].PageIndex})

	got, err := repo.GetByID(ctx, pages[0].ID)
	require.NoError(t, err)
	require.EqualValues(t, pages[0].ID, got.ID)
	require.Equal(t, examID, got.ExamID)

	_, err = repo.GetByID(ctx, 99999)
	require.ErrorIs(t, err, domain.ErrNotFound)
}

