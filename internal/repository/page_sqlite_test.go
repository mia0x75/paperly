// TestPageRepoInsertIfAbsent covers idempotent insert (the guard when a reorder task retries):
// conflicting rows are skipped, existing rows not overwritten, new rows inserted.
func TestPageRepoInsertIfAbsent(t *testing.T) {
	ctx := context.Background()
	db := openTestDB(t)
	repo := NewPageRepoSQLite(db)
	examID := insertExamForPages(t, db)
	_, err := repo.Insert(ctx, &domain.Page{
		ExamID: examID, PageIndex: 1, FilePath: "/orig/one.webp", SHA256: "orig",
	})
	require.NoError(t, err)

	inserted, err := repo.InsertIfAbsent(ctx, []*domain.Page{
		{ExamID: examID, PageIndex: 1, FilePath: "/dup/one.webp", SHA256: "dup"}, // conflict → skipped
		{ExamID: examID, PageIndex: 2, FilePath: "/new/two.webp", SHA256: "new"}, // new row → inserted
	})
	require.NoError(t, err)
	require.Equal(t, 1, inserted)

	pages, err := repo.ListByExam(ctx, examID)
	require.NoError(t, err)
	require.Len(t, pages, 2)
	require.Equal(t, "/orig/one.webp", pages[0].FilePath, "冲突行不得被覆盖")
	require.Equal(t, "/new/two.webp", pages[1].FilePath)
}
