// TestPageRepoRebuildPagesNotifies: the same-transaction enqueue wakes the Worker
// after the commit (this path does not go through TaskRepoSQLite.Insert).
func TestPageRepoRebuildPagesNotifies(t *testing.T) {
	ctx := context.Background()
	db := openTestDB(t)
	n := &countingNotifier{}
	repo := NewPageRepoSQLite(db).WithNotifier(n)
	examID := insertExamForPages(t, db)
	p1 := insertPageRow(t, repo, examID, 1)

	taskID, err := repo.RebuildPages(ctx, examID, nil, []domain.PageReorder{
		{ID: p1.ID, NewIndex: 5, NewFilePath: "/data/x/page_005.webp"},
	}, &domain.Task{Kind: domain.TaskKindReorderPages, Priority: 60, Status: domain.TaskStatusPending})
	require.NoError(t, err)
	require.Positive(t, taskID)
	require.Equal(t, 1, n.n, "reorder 入队提交后应唤醒一次")
}

