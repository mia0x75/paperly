// insertPageRow inserts a page conveniently and returns its pointer (path/hash generated by index).
func insertPageRow(t *testing.T, repo *PageRepoSQLite, examID int64, idx int) *domain.Page {
	t.Helper()
	id, err := repo.Insert(context.Background(), &domain.Page{
		ExamID: examID, PageIndex: idx,
		FilePath: fmt.Sprintf("/data/exams/%d/page_%03d.webp", examID, idx),
		SHA256:   fmt.Sprintf("sha-%d", idx),
	})
	require.NoError(t, err)
	return &domain.Page{ID: id, ExamID: examID, PageIndex: idx}
}

// TestPageRepoRebuildPagesWithEnqueue covers the core transaction:
// deleting pages + reordering + enqueuing the task succeed/rollback together; returns the task id.
func TestPageRepoRebuildPagesWithEnqueue(t *testing.T) {
	ctx := context.Background()
	db := openTestDB(t)
	repo := NewPageRepoSQLite(db)
	examID := insertExamForPages(t, db)
	p1 := insertPageRow(t, repo, examID, 1)
	p2 := insertPageRow(t, repo, examID, 2)
	p3 := insertPageRow(t, repo, examID, 3)

	taskID, err := repo.RebuildPages(ctx, examID, []int64{p2.ID}, []domain.PageReorder{
		{ID: p1.ID, NewIndex: 1, NewFilePath: fmt.Sprintf("/data/exams/%d/page_001.webp", examID)},
		{ID: p3.ID, NewIndex: 2, NewFilePath: fmt.Sprintf("/data/exams/%d/page_002.webp", examID)},
	}, &domain.Task{
		Kind: domain.TaskKindReorderPages, Priority: 60,
		Status: domain.TaskStatusPending, Detail: `{"exam_id":1}`,
	})
	require.NoError(t, err)
	require.Positive(t, taskID)

	pages, err := repo.ListByExam(ctx, examID)
	require.NoError(t, err)
	require.Len(t, pages, 2, "被删页应消失")
	require.Equal(t, []int{1, 2}, []int{pages[0].PageIndex, pages[1].PageIndex})
	require.Equal(t, p1.ID, pages[0].ID)
	require.Equal(t, p3.ID, pages[1].ID)
	require.Equal(t, fmt.Sprintf("/data/exams/%d/page_002.webp", examID), pages[1].FilePath,
		"存活页 file_path 应同步改到终名")

	// Task enqueued in the same transaction.
	var kind, priority, status int
	var detail string
	err = db.Read().GetContext(ctx, &kind, `SELECT kind FROM tasks WHERE id = ?`, taskID)
	require.NoError(t, err)
	require.Equal(t, domain.TaskKindReorderPages, kind)
	err = db.Read().GetContext(ctx, &priority, `SELECT priority FROM tasks WHERE id = ?`, taskID)
	require.NoError(t, err)
	require.Equal(t, 60, priority)
	err = db.Read().GetContext(ctx, &status, `SELECT status FROM tasks WHERE id = ?`, taskID)
	require.NoError(t, err)
	require.Equal(t, domain.TaskStatusPending, status)
	err = db.Read().GetContext(ctx, &detail, `SELECT detail FROM tasks WHERE id = ?`, taskID)
	require.NoError(t, err)
	require.JSONEq(t, `{"exam_id":1}`, detail)
}

// A failure must roll the whole reorder back: order and paths return to their
// originals and the enqueued task leaves no trace. A half-done state would
// permanently misalign disk and DB.
func TestPageRepoRebuildPagesRollbackOnError(t *testing.T) {
	ctx := context.Background()
	db := openTestDB(t)
	repo := NewPageRepoSQLite(db)
	examID := insertExamForPages(t, db)
	p1 := insertPageRow(t, repo, examID, 1)
	p2 := insertPageRow(t, repo, examID, 2)
	p3 := insertPageRow(t, repo, examID, 3)

	_, err := repo.RebuildPages(ctx, examID, []int64{p2.ID}, []domain.PageReorder{
		{ID: p1.ID, NewIndex: 1, NewFilePath: "/moved/one.webp"},
		{ID: p3.ID, NewIndex: 2, NewFilePath: "/moved/two.webp"},
		{ID: 99999, NewIndex: 3, NewFilePath: "/moved/bogus.webp"}, // missing → ErrNotFound
	}, &domain.Task{Kind: domain.TaskKindReorderPages, Priority: 60, Status: domain.TaskStatusPending})
	require.ErrorIs(t, err, domain.ErrNotFound)

	pages, err := repo.ListByExam(ctx, examID)
	require.NoError(t, err)
	require.Len(t, pages, 3, "删除必须回滚")
	require.Equal(t, []int{1, 2, 3}, []int{pages[0].PageIndex, pages[1].PageIndex, pages[2].PageIndex})
	require.Equal(t, fmt.Sprintf("/data/exams/%d/page_001.webp", examID), pages[0].FilePath, "回写必须回滚")

	var n int
	require.NoError(t, db.Read().GetContext(ctx, &n, `SELECT COUNT(*) FROM tasks`))
	require.Zero(t, n, "入队必须回滚")
}

// TestPageRepoRebuildPagesWithoutEnqueue: when enqueue=nil only reorders, does not enqueue a task.
