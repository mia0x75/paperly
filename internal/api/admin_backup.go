package api

import (
	"errors"

	"github.com/labstack/echo/v5"
	"net/http"

	"paperly/internal/api/dto"
	"paperly/internal/backup"
)

// DownloadBackup handles GET /api/admin/backups/:file_name/download.
//
// Uses c.Stream to return the bytes directly, **without writing a temp file**:
// backups are often hundreds of MB, so writing to disk first then returning
// would put three copies on the same Box at once.
func (h *AdminHandler) DownloadBackup(c *echo.Context) error {
	name := c.Param("file_name")
	rc, err := h.backup.StreamExport(c.Request().Context(), name)
	if err != nil {
		if errors.Is(err, backup.ErrBackupNotFound) {
			return fail(c, CodeNotFound, "backup not found", err.Error())
		}
		return fail(c, CodeInternal, "failed to read backup", err.Error())
	}
	defer func() { _ = rc.Close() }()

	// The filename comes from listBackupFiles' whitelist match, but could still
	// be a legal string generated by the backup flow itself; here we only strip
	// header characters, never echo the raw query parameter.
	downloadName := sanitizeHeaderValue(name)
	c.Response().Header().Set(echo.HeaderContentDisposition,
		`attachment; filename="`+downloadName+`"`)
	c.Response().Header().Set(echo.HeaderContentType, "application/gzip")
	return c.Stream(http.StatusOK, "application/gzip", rc)
}

// CreateBackup handles POST /api/admin/backup.
//
// VACUUM INTO plus integrity verification takes tens of seconds on a large DB,
// routinely exceeding a reverse proxy's default 30s; we do not loosen Echo's
// timeout (a global setting that should not change for one endpoint), but
// instead faithfully return the elapsed time and pruned count so ops can judge
// whether the gateway truncated the response.
func (h *AdminHandler) CreateBackup(c *echo.Context) error {
	manifest, pruned, err := h.backup.Create(c.Request().Context())
	if err != nil {
		return fail(c, CodeInternal, "backup failed", err.Error())
	}
	return ok(c, dto.NewBackupCreated(manifest, pruned))
}

// ListBackups handles GET /api/admin/backups.
func (h *AdminHandler) ListBackups(c *echo.Context) error {
	items, err := h.backup.List()
	if err != nil {
		return fail(c, CodeInternal, "failed to read backup list", err.Error())
	}
	lastAt, has, err := h.backup.LastBackupAt(c.Request().Context())
	if err != nil {
		return fail(c, CodeInternal, "failed to read latest backup time", err.Error())
	}
	return ok(c, dto.NewBackupListResponse(items, lastAt, has))
}
