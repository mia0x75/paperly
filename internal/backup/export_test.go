// tarNames unpacks the export stream and returns all entry names.
func tarNames(t *testing.T, r io.ReadCloser) []string {
	t.Helper()
	defer func() { require.NoError(t, r.Close()) }()

	gz, err := gzip.NewReader(r)
	require.NoError(t, err)
	defer func() { require.NoError(t, gz.Close()) }()

	var names []string
	tr := tar.NewReader(gz)
	for {
		hdr, err := tr.Next()
		if errors.Is(err, io.EOF) {
			break
		}
		require.NoError(t, err)
		names = append(names, hdr.Name)
		_, err = io.Copy(io.Discard, tr)
		require.NoError(t, err)
	}
	return names
}

// TestStreamExportPacksWholeBackupDir: the export must include db + manifest.
// Entry names carry the tier directory (weekly/...) so that on extraction you
// can tell at a glance which tier the package came from; per the requirements,
// a backup directory only holds db + manifest, no assets.
func TestStreamExportPacksWholeBackupDir(t *testing.T) {
	ctx := context.Background()
	svc, _, _, _ := newTestService(t, fixedNow())

	m, _, err := svc.Create(ctx)
	require.NoError(t, err)
	name := backupFilePrefix + m.Timestamp + ".db"

	rc, err := svc.StreamExport(ctx, name)
	require.NoError(t, err)
	names := tarNames(t, rc)
	require.Equal(t, []string{
		"weekly/" + name,
		"weekly/paperly_" + m.Timestamp + ".manifest.json",
	}, names)
}

// TestStreamExportRejectsUnknownName is a path-traversal guard test:
// ../../etc/passwd is not a name generated by the backup process and must be
// unreachable rather than read directly.
func TestStreamExportRejectsUnknownName(t *testing.T) {
	ctx := context.Background()
	svc, _, _, _ := newTestService(t, fixedNow())

	for _, bad := range []string{
		"../../etc/passwd", "/etc/passwd", "..", ".",
		backupFilePrefix + "notatime.db",
	} {
		_, err := svc.StreamExport(ctx, bad)
		require.ErrorIs(t, err, ErrBackupNotFound, "文件名 %q 必须被拒", bad)
	}
}

// TestStreamExportIsGzip checks the tar+gzip magic number, confirming the
// streaming pipe actually produces a compressed archive.
func TestStreamExportIsGzip(t *testing.T) {
	ctx := context.Background()
	svc, _, _, _ := newTestService(t, fixedNow())
	m, _, err := svc.Create(ctx)
	require.NoError(t, err)
	name := backupFilePrefix + m.Timestamp + ".db"

	rc, err := svc.StreamExport(ctx, name)
	require.NoError(t, err)
	defer func() { require.NoError(t, rc.Close()) }()

	magic := make([]byte, 2)
	_, err = io.ReadFull(rc, magic)
	require.NoError(t, err)
	require.Equal(t, []byte{0x1f, 0x8b}, magic)
}

// TestRestoreIsExplicitlyUnsupported: "restore is not done" is nailed down as
// an explicit error, so nobody thinks uploading a backup package silently works.
func TestRestoreIsExplicitlyUnsupported(t *testing.T) {
	svc, _, _, _ := newTestService(t, fixedNow())
	err := svc.Restore(context.Background(), "anything.tar.gz")
	require.Error(t, err)
	require.Contains(t, err.Error(), "8.2", "错误信息要指向需求条款，便于排查")
}

// TestExportSkipsIrregularFiles: when a symlink sneaks into the backup
// directory, it is exported as a 0-length regular file, never letting the
// extraction side follow a link.
func TestExportSkipsIrregularFiles(t *testing.T) {
	ctx := context.Background()
	svc, _, _, _ := newTestService(t, dailyNow())
	m, _, err := svc.Create(ctx)
	require.NoError(t, err)
	name := backupFilePrefix + m.Timestamp + ".db"

	dir := filepath.Join(svc.backupRoot(), string(tierDaily))
	require.NoError(t, os.Symlink("/etc/passwd", filepath.Join(dir, "sneaky")))

	rc, err := svc.StreamExport(ctx, name)
	require.NoError(t, err)
	defer func() { require.NoError(t, rc.Close()) }()

	gz, err := gzip.NewReader(rc)
	require.NoError(t, err)
	defer func() { require.NoError(t, gz.Close()) }()

	tr := tar.NewReader(gz)
	for {
		hdr, err := tr.Next()
		if errors.Is(err, io.EOF) {
			break
		}
		require.NoError(t, err)
		if strings.HasSuffix(hdr.Name, "sneaky") {
			require.NotEqual(t, byte(tar.TypeSymlink), hdr.Typeflag,
				"符号链接不得原样导出")
			require.Zero(t, hdr.Size, "不可信条目按 0 长度导出")
		}
	}
}

// fixedNow is the unified time in tests (2026-09-28 is Monday -> weekly tier).
func fixedNow() time.Time {
	return time.Date(2026, 9, 28, 3, 0, 0, 0, time.UTC)
}

// dailyNow lands on the daily tier (neither Monday nor the 1st).
func dailyNow() time.Time {
	return time.Date(2026, 9, 10, 3, 0, 0, 0, time.UTC)
}
