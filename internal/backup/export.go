var ErrBackupNotFound = errors.New("backup not found")

// ExportFileName is what the parent sees in the download directory.
const ExportFileName = "paperly-backup.tar.gz"

// StreamExport packs a backup directory into a tar.gz and streams it to w.
//
// Why export as a single file instead of having the parent copy the directory
// off the server: Box's target users run a single-machine service on their own
// computer, so what a parent wants is a file that "can be stored on cloud
// drive / sent by email"; a directory structure adds nothing to that.
//
// Security (download path traversal is the classic vulnerability for this kind
// of endpoint):
//   - fileName must be found in listBackupFiles' output — it only returns
//     names like `paperly_<12-digit timestamp>.db` generated by the backup
//     process itself, so an attacker-supplied "../../etc/passwd" never matches
//     and gets a 404;
//   - every tar entry name is a relative fileName, never a path the caller
//     might have assembled.
func (s *Service) StreamExport(ctx context.Context, fileName string) (io.ReadCloser, error) {
	dir, err := s.resolveBackupDir(ctx, fileName)
	if err != nil {
		return nil, err
	}

	pr, pw := io.Pipe()
	go func() {
		pw.CloseWithError(writeExport(ctx, pw, dir))
	}()
	return pr, nil
}

// resolveBackupDir finds fileName across the three tier directories.
func (s *Service) resolveBackupDir(_ context.Context, fileName string) (string, error) {
	for _, t := range tierOrder {
		dir := filepath.Join(s.backupRoot(), string(t))
		names, err := listBackupFiles(dir)
		if err != nil {
			return "", err
		}
		for _, name := range names {
			if name == fileName {
				return dir, nil
			}
		}
	}
	return "", fmt.Errorf("%w: %s", ErrBackupNotFound, fileName)
}

func writeExport(ctx context.Context, w io.Writer, dir string) error {
	gz := gzip.NewWriter(w)
	defer func() { _ = gz.Close() }()
	tw := tar.NewWriter(gz)
	defer func() { _ = tw.Close() }()

	base := filepath.Dir(dir)
	// Use os.ReadDir rather than filepath.WalkDir: a backup directory may
	// already contain tens of thousands of assets files, and WalkDir's
	// recursive tree is actually slower on large backups; only one flat level
	// is needed here (a backup directory is itself flat: db + manifest +
	// assets/ two levels).
	entries, err := os.ReadDir(dir)
	if err != nil {
		return fmt.Errorf("read backup dir: %w", err)
	}
	for _, e := range entries {
		if err := ctx.Err(); err != nil {
			return err
		}
		if err := writeTarEntry(tw, base, dir, e); err != nil {
			return err
		}
	}
	return nil
}

func writeTarEntry(tw *tar.Writer, base, dir string, e os.DirEntry) error {
	full := filepath.Join(dir, e.Name())
	// The entry name must be relative to the backup root. Compute it with
	// relpath explicitly; splicing e.Name() directly under nested directories
	// (assets/exams/) would lose levels, flattening everything to the root on
	// extraction.
	rel, err := filepath.Rel(base, full)
	if err != nil {
		return fmt.Errorf("rel %s: %w", full, err)
	}
	info, err := e.Info()
	if err != nil {
		return fmt.Errorf("stat %s: %w", full, err)
	}

	if e.IsDir() {
		if err := tw.WriteHeader(&tar.Header{
			Name: filepath.ToSlash(rel) + "/",
			Mode: 0o755,
		}); err != nil {
			return fmt.Errorf("tar header dir %s: %w", rel, err)
		}
		children, err := os.ReadDir(full)
		if err != nil {
			return fmt.Errorf("read dir %s: %w", full, err)
		}
		for _, child := range children {
			if err := writeTarEntry(tw, base, full, child); err != nil {
				return err
			}
		}
		return nil
	}

	// Non-regular files (symlinks, device files): export as 0-length regular
	// files rather than copying them as-is. A backup directory should not have
	// links; if one somehow appears, better to export an empty file than let
	// the extraction side follow a link out of the backup root.
	size := info.Size()
	if !info.Mode().IsRegular() {
		size = 0
	}

	if err := tw.WriteHeader(&tar.Header{
		Name: filepath.ToSlash(rel),
		Mode: 0o600,
		Size: size,
	}); err != nil {
		return fmt.Errorf("tar header %s: %w", rel, err)
	}
	if size == 0 {
		return nil
	}

	f, err := os.Open(full) //nolint:gosec // full is composed from backupRoot + an already-validated file name; no user-controlled fragment.
	if err != nil {
		return fmt.Errorf("open %s: %w", full, err)
	}
	defer func() { _ = f.Close() }()
	if _, err := io.Copy(tw, f); err != nil {
		return fmt.Errorf("copy %s: %w", full, err)
	}
	return nil
}

// Restore is deliberately not implemented.
//
// The requirements pin down "asset files are not included in backups — backups
// only cover the DB". A complete "upload a backup package and restore" would
// have to restore both the DB and assets/, which conflicts with that; and
// restoring only the DB would lose all page images (exams are tightly bound to
// their volume, and deleting a volume deletes its directory). Until the
// requirements define a restore semantics (write-stall window, conflict
// handling, assets alignment rules), this returns an explicit error rather
// than silently doing half the job.
func (s *Service) Restore(_ context.Context, _ string) error {
	return errors.New("restore from uploaded backup is not supported: " +
		"REQUIREMENTS 8.2 limits backups to the DB; asset files are not included; " +
		"restore semantics (write-stall window / assets alignment) are not defined in requirements yet")
}
